import { mkdir, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = dirname(fileURLToPath(new URL('../package.json', import.meta.url)))
const tempRoot = join(root, '.tmp', 'ieee-runtime')
const entry = join(root, 'backend', 'p2pmd', 'ieee-browser-entry.js')
const output = join(root, 'backend', 'p2pmd', 'ieee-runtime.mjs')

await rm(tempRoot, { force: true, recursive: true })
await mkdir(tempRoot, { recursive: true })

const result = await build({
  bundle: true,
  entryPoints: [entry],
  format: 'iife',
  logLevel: 'silent',
  minify: true,
  platform: 'browser',
  target: 'es2019',
  write: false
})

await writeFile(output, [
  '/* eslint-disable */',
  '// Generated by scripts/generate-ieee-runtime.mjs. Do not edit.',
  `const ieeeBrowserScript = ${JSON.stringify(result.outputFiles[0].text)}`,
  '',
  'export default ieeeBrowserScript',
  ''
].join('\n'))

await rm(tempRoot, { force: true, recursive: true })
