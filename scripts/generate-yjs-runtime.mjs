import { mkdir, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = dirname(fileURLToPath(new URL('../package.json', import.meta.url)))
const tempRoot = join(root, '.tmp')
const tempDir = join(tempRoot, 'yjs-runtime')
const entry = join(tempDir, 'entry.mjs')
const output = join(root, 'backend', 'p2pmd', 'yjs-runtime.mjs')

await rm(tempRoot, { force: true, recursive: true })
await mkdir(tempDir, { recursive: true })
await writeFile(entry, [
  "import * as Y from 'yjs'",
  'globalThis.Y = Y',
  ''
].join('\n'))

const result = await build({
  bundle: true,
  entryPoints: [entry],
  format: 'iife',
  globalName: '__PeerSkyYjsRuntime',
  logLevel: 'silent',
  minify: true,
  platform: 'browser',
  target: 'es2019',
  write: false
})

const script = result.outputFiles[0].text
await writeFile(output, [
  '/* eslint-disable */',
  '// Generated by scripts/generate-yjs-runtime.mjs from node_modules/yjs.',
  `const yjsBrowserScript = ${JSON.stringify(script)}`,
  '',
  'export default yjsBrowserScript',
  ''
].join('\n'))

await rm(tempRoot, { force: true, recursive: true })
