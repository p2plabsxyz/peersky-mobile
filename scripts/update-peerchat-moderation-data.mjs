import { createHash } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const SOURCE_COMMIT = 'c7f07f753cfc963bf933e7cc848d6e437503848a'
const SOURCE_BASE = `https://raw.githubusercontent.com/p2plabsxyz/peerchat/${SOURCE_COMMIT}/lib`
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT = path.join(ROOT, 'backend', 'peerchat', 'moderation-data.mjs')
const SOURCES = {
  'bad-words.txt': {
    maxBytes: 1024 * 1024,
    sha256: '0a79cbae73923435ad647d7d70ead78125ffe952d8a4596e03759aeee1517da9'
  },
  'adult-domains.hosts': {
    maxBytes: 8 * 1024 * 1024,
    sha256: '9e3942ad6411ac72117be5a04b5adb596f5489c10ab995ee71a82d76ed3fe932'
  }
}

const badWordsText = await loadSource('bad-words.txt')
const adultDomainsText = await loadSource('adult-domains.hosts')
const badWords = [...parseBadWords(badWordsText)].sort()
const adultDomains = [...parseAdultDomains(adultDomainsText)].sort()

const generated = '// Generated by scripts/update-peerchat-moderation-data.mjs. Do not edit.\n' +
  `// Source: p2plabsxyz/peerchat@${SOURCE_COMMIT} (MIT).\n` +
  '// adult-domains.hosts is sourced by PeerChat from StevenBlack/hosts.\n' +
  `export const PEERCHAT_BAD_WORDS = Object.freeze(${JSON.stringify(badWords)})\n\n` +
  `export const PEERCHAT_ADULT_DOMAINS = Object.freeze(${JSON.stringify(adultDomains)})\n`

await mkdir(path.dirname(OUTPUT), { recursive: true })
await writeFile(OUTPUT, generated)
console.log(`Wrote ${badWords.length} words and ${adultDomains.length} domains to ${path.relative(ROOT, OUTPUT)}`)

async function loadSource (name) {
  const response = await fetch(`${SOURCE_BASE}/${name}`)
  if (!response.ok) throw new Error(`${name} download failed with HTTP ${response.status}`)
  const expected = SOURCES[name]
  const declaredBytes = Number(response.headers.get('content-length'))
  if (Number.isFinite(declaredBytes) && declaredBytes > expected.maxBytes) {
    throw new Error(`${name} exceeds the ${expected.maxBytes}-byte limit`)
  }

  const bytes = await readCapped(response, expected.maxBytes)
  const digest = createHash('sha256').update(bytes).digest('hex')
  if (digest !== expected.sha256) throw new Error(`${name} failed its SHA-256 integrity check`)
  return new TextDecoder().decode(bytes)
}

async function readCapped (response, maxBytes) {
  if (!response.body?.getReader) throw new Error('A streaming fetch implementation is required')
  const reader = response.body.getReader()
  const chunks = []
  let byteLength = 0
  try {
    while (true) {
      const { value, done } = await reader.read()
      if (done) break
      byteLength += value.byteLength
      if (byteLength > maxBytes) throw new Error(`Moderation source exceeds the ${maxBytes}-byte limit`)
      chunks.push(value)
    }
  } finally {
    reader.releaseLock()
  }

  const output = new Uint8Array(byteLength)
  let offset = 0
  for (const chunk of chunks) {
    output.set(chunk, offset)
    offset += chunk.byteLength
  }
  return output
}

function parseBadWords (text) {
  const words = new Set()
  for (const line of text.split(/\r?\n/)) {
    const word = line.trim().toLowerCase()
    if (word && /^[a-z0-9'.-]+$/i.test(word)) words.add(word)
  }
  return words
}

function parseAdultDomains (text) {
  const domains = new Set()
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.replace(/#.*/, '').trim()
    if (!line) continue
    const parts = line.split(/\s+/)
    const candidate = /^(?:0[.]0[.]0[.]0|127[.]0[.]0[.]1|::1)$/i.test(parts[0]) && parts[1]
      ? parts[1]
      : parts[0]
    const domain = candidate.toLowerCase()
    if (!/^(?=.{1,253}$)(?!-)(?:[a-z0-9-]{1,63}[.])+[a-z0-9-]{2,63}$/i.test(domain)) continue
    domains.add(domain.startsWith('www.') ? domain.slice(4) : domain)
  }
  return domains
}
