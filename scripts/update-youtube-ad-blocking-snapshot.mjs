console.log(`Updated YouTube ad-blocking scriptlets from ${sourceCommit}.`)

function readYoutubeAdBreakPath (contents) {
  const rules = JSON.parse(contents)
  const rule = rules.find((candidate) => (
    candidate?.action?.type === 'block' &&
    candidate?.condition?.urlFilter === '||youtube.com/youtubei/v1/player/ad_break' &&
    candidate.condition.resourceTypes?.includes('xmlhttprequest')
  ))
  if (!rule) throw new Error('The pinned YouTube ad-break rule has an unexpected shape.')
  return '/youtubei/v1/player/ad_break'
}

async function downloadVerified (sourcePath, expectedHash) {
  const controller = new AbortController()
  const timeout = setTimeout(() => controller.abort(), timeoutMs)

  try {
    const response = await fetch(`${sourceBaseUrl}/${sourcePath}`, {
      headers: { Accept: 'text/plain' },
      signal: controller.signal
    })
    if (!response.ok) throw new Error(`${sourcePath} returned HTTP ${response.status}.`)

    const declaredLength = Number(response.headers.get('content-length'))
    if (Number.isFinite(declaredLength) && declaredLength > maxSourceBytes) {
      throw new Error(`${sourcePath} exceeds the size limit.`)
    }

    const reader = response.body?.getReader()
    if (!reader) throw new Error(`${sourcePath} did not return a readable body.`)
    const chunks = []
    let byteLength = 0
    while (true) {
      const { done, value } = await reader.read()
      if (done) break
      byteLength += value.byteLength
      if (byteLength > maxSourceBytes) {
        await reader.cancel()
        throw new Error(`${sourcePath} exceeds the size limit.`)
      }
      chunks.push(value)
    }

    const bytes = Buffer.concat(chunks, byteLength)
    const actualHash = createHash('sha256').update(bytes).digest('hex')
    if (actualHash !== expectedHash) {
      throw new Error(`${sourcePath} failed its SHA-256 integrity check.`)
    }
    return bytes.toString('utf8')
  } finally {
    clearTimeout(timeout)
  }
}
