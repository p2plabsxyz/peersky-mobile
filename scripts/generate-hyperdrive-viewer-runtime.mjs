import { realpathSync } from 'node:fs'
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

// Turns the Hyperdrive viewer under assets/hyperdrive-viewer, a copy of the
// viewer/ folder of p2plabsxyz/upload, into one module the Bare bundle can
// carry, since bare-pack only packs JavaScript. Output is sorted so
// regenerating from the same files never changes the committed file.

const root = dirname(fileURLToPath(new URL('../package.json', import.meta.url)))
export const sourceDir = join(root, 'assets', 'hyperdrive-viewer')
export const outputFile = join(root, 'backend', 'hyperdrive-viewer', 'viewer-runtime.mjs')

// Credits and notes travel in Settings > Licenses and the repo, not in the
// page: nothing in the viewer loads them, and no Markdown file of its own.
const SKIPPED_FILES = new Set(['LICENSE', 'NOTICE'])

export function isViewerNote (name) {
  return SKIPPED_FILES.has(name) || name.toLowerCase().endsWith('.md')
}
const TEXT_EXTENSIONS = new Set(['.css', '.html', '.js', '.json', '.mjs', '.svg', '.txt', '.webmanifest'])

async function collectFiles (dir) {
  const entries = await readdir(dir, { withFileTypes: true })
  const files = []

  for (const entry of entries) {
    if (entry.name.startsWith('.')) continue
    const entryPath = join(dir, entry.name)

    if (entry.isDirectory()) {
      files.push(...await collectFiles(entryPath))
    } else if (entry.isFile() && !isViewerNote(entry.name)) {
      files.push(entryPath)
    }
  }

  return files
}

/** The module's source, from the files in assets/hyperdrive-viewer. */
export async function buildViewerRuntime (dir = sourceDir) {
  const files = (await collectFiles(dir)).sort()
  const assets = {}

  for (const filePath of files) {
    const key = relative(dir, filePath).split(sep).join('/')
    const dot = key.lastIndexOf('.')
    const extension = dot > key.lastIndexOf('/') ? key.slice(dot).toLowerCase() : ''
    const bytes = await readFile(filePath)

    assets[key] = TEXT_EXTENSIONS.has(extension)
      ? { encoding: 'utf8', content: bytes.toString('utf8') }
      : { encoding: 'base64', content: bytes.toString('base64') }
  }

  return [
    '/* eslint-disable */',
    '// Generated by scripts/generate-hyperdrive-viewer-runtime.mjs from assets/hyperdrive-viewer.',
    `const viewerAssets = ${JSON.stringify(assets)}`,
    '',
    'export default viewerAssets',
    ''
  ].join('\n')
}

/**
 * The viewer's files its own files ask for, by the absolute path the page
 * loads them from (/hyperdrive/viewer/...), that are not in the copy. A page
 * that imports a missing module does not start at all.
 */
export async function missingViewerFiles (dir = sourceDir) {
  const files = await collectFiles(dir)
  const present = new Set(files.map((filePath) => relative(dir, filePath).split(sep).join('/')))
  const missing = new Set()
  for (const filePath of files) {
    if (!/\.(?:css|html|m?js)$/i.test(filePath)) continue
    const text = (await readFile(filePath)).toString('utf8')
    for (const match of text.matchAll(/["'(]\/hyperdrive\/viewer\/([^"'()\s?#]+)/g)) {
      if (!present.has(match[1])) missing.add(match[1])
    }
  }
  return [...missing].sort()
}

/** Writes backend/hyperdrive-viewer/viewer-runtime.mjs. */
export async function writeViewerRuntime () {
  await mkdir(dirname(outputFile), { recursive: true })
  await writeFile(outputFile, await buildViewerRuntime())
}

// Run as a script, not imported by a test or by the sync script. Node gives
// the module its real path, so the script's is compared as one too.
function isMain () {
  try {
    return Boolean(process.argv[1]) && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)
  } catch {
    return false
  }
}

if (isMain()) await writeViewerRuntime()
