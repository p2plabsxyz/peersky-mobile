/**
 * The bird for a page that would not load: the badge drawing with its eye
 * shut, lifted off its background, with a tear at the low corner of the eye.
 * The ring and the colour behind the bird come away outside first, so no flood
 * reaches the bird's own black outline. The eye's position is a fraction of
 * the bird's measured box, so the same numbers hold at any size.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { PNG } from 'pngjs'

const root = new URL('../', import.meta.url)
const SOURCE = new URL('assets/app-icons/sad-bird-source.png', root)
const FALLBACK = new URL('assets/images/logo.png', root)
const OUTPUT_SIZE = 320

// Measured from logo.png, as fractions of the bird's bounding box.
const EYE = { left: 0.577, top: 0.093, bottom: 0.374, width: 0.248 }
// Almost white, the way a tear actually looks, with the faintest blue in it
// so it belongs to this drawing rather than sitting on top of it.
const TEAR_COLOUR = [0xf0, 0xf8, 0xff]

const usingBadge = existsSync(SOURCE)
const image = PNG.sync.read(readFileSync(usingBadge ? SOURCE : FALLBACK))

if (usingBadge) removeBackground(image)
const box = measureOpaque(image)
// A drawing supplied here already has its eye shut. The everyday bird does
// not, so closing it is the fallback's job and nobody else's.
if (!usingBadge) closeEye(image, box)
drawTear(image, box)

const out = scale(crop(image, box), OUTPUT_SIZE)
const encoded = PNG.sync.write(out, { deflateLevel: 9 }).toString('base64')

writeFileSync(
  new URL('app/browser-error-art.mjs', root),
  [
    '// Generated by scripts/generate-sad-bird.mjs. The error page is handed to',
    '// the WebView as a string with no address behind it, so its picture has to',
    '// travel inside the page.',
    `export const SAD_BIRD_DATA_URI = 'data:image/png;base64,${encoded}'`,
    ''
  ].join('\n')
)

console.log(
  `${usingBadge ? 'badge' : 'logo.png'} -> browser-error-art.mjs, ` +
  `${OUTPUT_SIZE}px, ${Math.round(encoded.length / 1024)}KB inlined`
)

/**
 * Clears the badge, one ring of colour at a time.
 *
 * A single flood would reach the bird's outline through the black of the ring
 * and eat it. Going outward-in by colour, and only once each, stops at the
 * bird because the pass that could cross black has already finished.
 */
function removeBackground (image) {
  const total = image.width * image.height
  const cleared = new Uint8Array(total)
  const at = (index) => index * 4

  const isClear = (i) => image.data[at(i) + 3] < 40
  const isPale = (i) => {
    const [r, g, b] = [image.data[at(i)], image.data[at(i) + 1], image.data[at(i) + 2]]
    return r > 225 && g > 225 && b > 225
  }
  const isInk = (i) => {
    const [r, g, b] = [image.data[at(i)], image.data[at(i) + 1], image.data[at(i) + 2]]
    return r < 90 && g < 90 && b < 90
  }
  // The badge colour, and the soft shadow the bird casts on it: green at least
  // as strong as blue, which is what separates it from the bird's own blue.
  const isBadge = (i) => {
    const [r, g, b] = [image.data[at(i)], image.data[at(i) + 1], image.data[at(i) + 2]]
    return g >= b - 8 && g > r + 20
  }

  const flood = (accepts) => {
    const queue = []
    for (let i = 0; i < total; i++) {
      if (!cleared[i]) continue
      queue.push(i)
    }
    if (queue.length === 0) {
      for (let x = 0; x < image.width; x++) {
        queue.push(x, (image.height - 1) * image.width + x)
      }
      for (let y = 0; y < image.height; y++) {
        queue.push(y * image.width, y * image.width + image.width - 1)
      }
    }

    while (queue.length > 0) {
      const index = queue.pop()
      const x = index % image.width
      const y = (index - x) / image.width

      for (const [nx, ny] of [[x - 1, y], [x + 1, y], [x, y - 1], [x, y + 1]]) {
        if (nx < 0 || ny < 0 || nx >= image.width || ny >= image.height) continue
        const next = ny * image.width + nx
        if (cleared[next] || !accepts(next)) continue
        cleared[next] = 1
        queue.push(next)
      }
    }
  }

  // Seed the border itself, then take the outside, the ring, and the colour.
  for (let x = 0; x < image.width; x++) {
    for (const i of [x, (image.height - 1) * image.width + x]) {
      if (isClear(i) || isPale(i)) cleared[i] = 1
    }
  }
  flood((i) => isClear(i) || isPale(i))
  flood(isInk)
  flood((i) => isBadge(i) || isPale(i))

  for (let i = 0; i < total; i++) {
    if (cleared[i]) image.data[at(i) + 3] = 0
  }
}

// Half shut, hanging lowest on the side away from the beak. A level lid is a
// blink; the slope is what makes it a frown.
function closeEye (image, box) {
  const ink = darkestOpaque(image)
  const left = Math.round(box.left + box.width * EYE.left)
  const right = Math.round(box.left + box.width * (EYE.left + EYE.width))
  const top = Math.round(box.top + box.height * EYE.top)
  const bottom = Math.round(box.top + box.height * EYE.bottom)

  for (let y = top; y <= bottom; y++) {
    for (let x = left; x <= right; x++) {
      const u = (x - left) / (right - left)
      const v = (y - top) / (bottom - top)
      if (Math.hypot((u - 0.5) * 2, (v - 0.5) * 2) > 1) continue
      if (v > 0.62 - u * 0.34) continue
      setOpaque(image, x, y, ink)
    }
  }
}

/**
 * A tear running from the eye: a half circle at the bottom, curving in to a
 * point at the lid. Width and length are set separately. Narrow reads as a
 * tear and wide as a bubble, while length makes it fall, and tying both to
 * one radius made a thin tear come out as a dot.
 */
function drawTear (image, box) {
  const eyeWidth = box.width * EYE.width
  const halfWidth = Math.max(2, Math.round(eyeWidth * 0.13))
  const length = Math.max(6, Math.round(eyeWidth * 0.66))
  const edge = Math.max(1, Math.round(halfWidth * 0.32))
  const ink = darkestOpaque(image)

  const centreX = Math.round(box.left + box.width * (EYE.left + EYE.width * 0.62))
  // Just clear of the lid, so it reads as having fallen from the eye rather
  // than still being in it.
  const top = Math.round(box.top + box.height * EYE.bottom + halfWidth * 0.6)
  const roundFrom = top + length - halfWidth

  for (let y = top; y <= top + length; y++) {
    const half = y <= roundFrom
      ? halfWidth * ((y - top) / Math.max(1, roundFrom - top)) ** 0.6
      : Math.sqrt(Math.max(0, halfWidth * halfWidth - (y - roundFrom) ** 2))
    if (half < 0.5) continue

    for (let x = Math.round(centreX - half); x <= Math.round(centreX + half); x++) {
      const inset = half - Math.abs(x - centreX)
      setOpaque(image, x, y, inset < edge ? ink : TEAR_COLOUR)
    }
  }
}

function measureOpaque (image) {
  let left = image.width
  let top = image.height
  let right = -1
  let bottom = -1

  for (let y = 0; y < image.height; y++) {
    for (let x = 0; x < image.width; x++) {
      if (image.data[(y * image.width + x) * 4 + 3] <= 40) continue
      if (x < left) left = x
      if (x > right) right = x
      if (y < top) top = y
      if (y > bottom) bottom = y
    }
  }

  return { left, top, right, bottom, width: right - left + 1, height: bottom - top + 1 }
}

function darkestOpaque (image) {
  let best = [0, 0, 0]
  let bestSum = 255 * 3

  for (let i = 0; i < image.width * image.height; i++) {
    const index = i * 4
    if (image.data[index + 3] < 250) continue
    const sum = image.data[index] + image.data[index + 1] + image.data[index + 2]
    if (sum < bestSum) {
      bestSum = sum
      best = [image.data[index], image.data[index + 1], image.data[index + 2]]
    }
  }
  return best
}

function setOpaque (image, x, y, colour) {
  if (x < 0 || y < 0 || x >= image.width || y >= image.height) return
  const index = (y * image.width + x) * 4
  image.data[index] = colour[0]
  image.data[index + 1] = colour[1]
  image.data[index + 2] = colour[2]
  image.data[index + 3] = 255
}

// Square, so the page can size it without deciding which way to letterbox.
function crop (image, box) {
  const size = Math.max(box.width, box.height)
  const out = new PNG({ width: size, height: size })
  out.data.fill(0)
  const offsetX = Math.round((size - box.width) / 2)
  const offsetY = Math.round((size - box.height) / 2)

  for (let y = 0; y < box.height; y++) {
    for (let x = 0; x < box.width; x++) {
      const from = ((box.top + y) * image.width + box.left + x) * 4
      const to = ((y + offsetY) * size + x + offsetX) * 4
      for (let channel = 0; channel < 4; channel++) {
        out.data[to + channel] = image.data[from + channel]
      }
    }
  }
  return out
}

// Box filter through premultiplied alpha, so the transparent edge does not
// drag black into the outline.
function scale (image, size) {
  const out = new PNG({ width: size, height: size })
  const step = image.width / size

  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      let red = 0
      let green = 0
      let blue = 0
      let alpha = 0
      let samples = 0

      for (let sy = Math.floor(y * step); sy < Math.max(Math.floor(y * step) + 1, Math.floor((y + 1) * step)); sy++) {
        for (let sx = Math.floor(x * step); sx < Math.max(Math.floor(x * step) + 1, Math.floor((x + 1) * step)); sx++) {
          if (sy >= image.height || sx >= image.width) continue
          const index = (sy * image.width + sx) * 4
          const a = image.data[index + 3] / 255
          red += image.data[index] * a
          green += image.data[index + 1] * a
          blue += image.data[index + 2] * a
          alpha += a
          samples++
        }
      }

      const index = (y * size + x) * 4
      out.data[index] = alpha > 0 ? Math.round(red / alpha) : 0
      out.data[index + 1] = alpha > 0 ? Math.round(green / alpha) : 0
      out.data[index + 2] = alpha > 0 ? Math.round(blue / alpha) : 0
      out.data[index + 3] = samples > 0 ? Math.round((alpha / samples) * 255) : 0
    }
  }
  return out
}
