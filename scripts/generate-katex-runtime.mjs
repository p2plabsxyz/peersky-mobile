import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const katexRoot = path.join(root, 'node_modules', 'katex', 'dist')
const cssPath = path.join(katexRoot, 'katex.min.css')
const outputPath = path.join(root, 'backend', 'p2pmd', 'katex-runtime.mjs')

let css = fs.readFileSync(cssPath, 'utf8')

// Keep the compact WOFF2 source only, then embed it so previews and published
// Hyper pages render math offline without separate asset routing.
css = css.replace(
  /src:url\(fonts\/([^)]+[.]woff2)\) format\("woff2"\),url\(fonts\/[^)]+[.]woff\) format\("woff"\),url\(fonts\/[^)]+[.]ttf\) format\("truetype"\)/g,
  (_source, filename) => {
    const bytes = fs.readFileSync(path.join(katexRoot, 'fonts', filename))
    return `src:url(data:font/woff2;base64,${bytes.toString('base64')}) format("woff2")`
  }
)

if (/url\(fonts\//.test(css)) {
  throw new Error('Unable to embed every KaTeX font reference.')
}

const output = '// Generated by scripts/generate-katex-runtime.mjs. Do not edit.\n' +
  `const katexCss = ${JSON.stringify(css)}\n\n` +
  'export default katexCss\n'

fs.writeFileSync(outputPath, output)
console.log(`Generated ${path.relative(root, outputPath)}`)
